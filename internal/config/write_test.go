// collectYAMLKeys gathers the yaml tag of every field reachable from typ.
func collectYAMLKeys(t *testing.T, typ reflect.Type, out map[string]struct{}) {
	t.Helper()
	for i := 0; i < typ.NumField(); i++ {
		f := typ.Field(i)
		tag, _, _ := strings.Cut(f.Tag.Get("yaml"), ",")
		if tag == "" || tag == "-" {
			continue
		}
		// Rubric dimensions live in .qode/scoring.yaml, never in qode.yaml, so the
		// walk stops here instead of descending into RubricConfig/DimensionConfig.
		if tag == "rubrics" {
			continue
		}
		// The deprecated ide: key is read-only: WriteDefault never emits it.
		if tag == legacyAgentsKey {
			continue
		}
		out[tag] = struct{}{}
		if f.Type.Kind() == reflect.Struct {
			collectYAMLKeys(t, f.Type, out)
		}
	}
}

func TestWriteDefault_CoversEveryConfigKey(t *testing.T) {
	t.Parallel()

	_, data := writeDefaultInto(t, "")
	rendered := string(data)

	keys := map[string]struct{}{}
	collectYAMLKeys(t, reflect.TypeOf(Config{}), keys)
	if len(keys) < 10 {
		t.Fatalf("key walk collected only %d keys, expected the full schema", len(keys))
	}

	for key := range keys {
		// Match the key as a YAML key — active or commented out — so comment prose
		// that happens to contain the word cannot satisfy the assertion.
		pattern := regexp.MustCompile(`(?m)^\s*(#\s*)?` + regexp.QuoteMeta(key) + `:`)
		if !pattern.MatchString(rendered) {
			t.Errorf("generated qode.yaml has no %q key, active or commented", key)
		}
	}
}

func TestWriteDefault_IsCommented(t *testing.T) {
	t.Parallel()

	// Guard against a vacuous assertion: the comments below are derived from these
	// totals, and the three rubrics do not share a maximum.
	if got := rubricTotal("review"); got != 12 {
		t.Fatalf("review rubric total = %d, want 12", got)
	}
	if got := rubricTotal("security"); got != 10 {
		t.Fatalf("security rubric total = %d, want 10", got)
	}
	if got := rubricTotal("refine"); got != 25 {
		t.Fatalf("refine rubric total = %d, want 25", got)
	}

	_, data := writeDefaultInto(t, "")
	rendered := string(data)

	for _, want := range []string{
		"# qode configuration. Full reference:",
		"# docs/qode-yaml-reference.md",
		"written by qode init; identifies the config format version",
		"# Minimum scores a review must reach.",
		"default review rubric total is 12",
		"default security rubric total is 10",
		"# Scoring engine. Rubric dimensions live in .qode/scoring.yaml, not here.",
		"# target_score: 25 # override the /qode-plan-refine pass threshold",
		"enforce step ordering; exit 1 when a gate fails",
		"# Agent assets generated by 'qode init'. Set false to skip one.",
		".cursor/commands/*.mdc",
		".claude/commands/*.md",
		".agents/skills/*/SKILL.md",
		".opencode/commands/*.md",
		"# Where 'qode knowledge' stores and looks up entries.",
		"# Command whose stdout is the diff reviewed by 'qode review'.",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("generated qode.yaml is missing comment %q", want)
		}
	}

	// The ambiguous shared wording would be a false claim about min_security_score.
	if strings.Contains(rendered, "default rubric total is 12") {
		t.Error("generated qode.yaml uses the ambiguous shared rubric comment")
	}

	scoringAt := strings.Index(rendered, "\nscoring:")
	targetAt := strings.Index(rendered, "# target_score:")
	strictAt := strings.Index(rendered, "strict:")
	if scoringAt < 0 || targetAt < scoringAt || strictAt < targetAt {
		t.Errorf("commented target_score is not inside the scoring block above strict (scoring=%d target=%d strict=%d)",
			scoringAt, targetAt, strictAt)
	}
}

