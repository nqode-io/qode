func TestUpgrade_VersionStamping(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name          string
		seedVersion   string
		binaryVersion string
		wantChanged   bool
		wantLine      string
	}{
		{name: "empty binary version leaves it alone", seedVersion: "0.1.0", binaryVersion: "", wantLine: "qode_version: 0.1.0"},
		{name: "dev binary leaves it alone", seedVersion: "0.1.0", binaryVersion: "dev", wantLine: "qode_version: 0.1.0"},
		{name: "missing key is added by a dev binary", binaryVersion: "dev", wantChanged: true, wantLine: "qode_version: dev"},
		{name: "release binary re-stamps", seedVersion: "0.1.0", binaryVersion: "0.4.0-beta", wantChanged: true, wantLine: "qode_version: 0.4.0-beta"},
		{name: "numeric version stays a string", seedVersion: "0.1.0", binaryVersion: "1.0", wantChanged: true, wantLine: `qode_version: "1.0"`},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			seed := tc.seedVersion
			if seed == "" {
				seed = "0.0.0"
			}
			dir, data := writeDefaultInto(t, seed)
			if tc.seedVersion == "" {
				data = stripVersionKey(t, data)
				if err := os.WriteFile(filepath.Join(dir, ConfigFileName), data, 0644); err != nil {
					t.Fatalf("rewriting seed: %v", err)
				}
			}

			changed, err := Upgrade(context.Background(), dir, tc.binaryVersion)
			if err != nil {
				t.Fatalf("Upgrade: %v", err)
			}
			if changed != tc.wantChanged {
				t.Errorf("changed = %v, want %v", changed, tc.wantChanged)
			}
			if got := string(readConfig(t, dir)); !strings.Contains(got, tc.wantLine) {
				t.Errorf("upgraded config does not contain %q:\n%s", tc.wantLine, got)
			}
		})
	}
}

// stripVersionKey removes the qode_version line so a seed file lacks the key.
func stripVersionKey(t *testing.T, data []byte) []byte {
	t.Helper()
	var kept []string
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "qode_version:") {
			continue
		}
		kept = append(kept, line)
	}
	return []byte(strings.Join(kept, "\n"))
}

func TestUpgrade_SecondPassIsIdempotent(t *testing.T) {
	t.Parallel()

	dir := seedConfig(t, "qode_version: 0.1.0\n")

	if _, err := Upgrade(context.Background(), dir, "dev"); err != nil {
		t.Fatalf("first Upgrade: %v", err)
	}
	path := filepath.Join(dir, ConfigFileName)
	before := readConfig(t, dir)
	statBefore, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}

	changed, err := Upgrade(context.Background(), dir, "dev")
	if err != nil {
		t.Fatalf("second Upgrade: %v", err)
	}
	if changed {
		t.Error("second Upgrade reported a change")
	}
	if got := readConfig(t, dir); string(got) != string(before) {
		t.Errorf("second Upgrade rewrote the file:\n%s", got)
	}
	statAfter, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if !statAfter.ModTime().Equal(statBefore.ModTime()) {
		t.Error("second Upgrade touched the file's mtime")
	}
}

