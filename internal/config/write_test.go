func TestWriteDefault_ExistingFile(t *testing.T) {
	t.Parallel()

	const existing = "qode_version: 0.1.0\n"

	tests := []struct {
		name      string
		overwrite bool
		wantErr   error
		wantKept  bool
	}{
		{name: "refuses without overwrite", overwrite: false, wantErr: ErrConfigExists, wantKept: true},
		{name: "replaces with overwrite", overwrite: true},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			dir := seedConfig(t, existing)
			err := WriteDefault(context.Background(), dir, "0.4.0-beta", tc.overwrite)
			if !errors.Is(err, tc.wantErr) {
				t.Fatalf("WriteDefault error = %v, want %v", err, tc.wantErr)
			}

			got := string(readConfig(t, dir))
			if tc.wantKept {
				if got != existing {
					t.Errorf("existing file was modified: %q", got)
				}
				return
			}
			if !strings.Contains(got, "# Minimum scores a review must reach.") {
				t.Errorf("file was not replaced by the commented defaults:\n%s", got)
			}
		})
	}
}

