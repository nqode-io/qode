// writeDefaultInto renders the default document into a fresh directory and returns
// the directory and the bytes on disk.
func writeDefaultInto(t *testing.T, binaryVersion string) (string, []byte) {
	t.Helper()
	dir := t.TempDir()
	if err := WriteDefault(context.Background(), dir, binaryVersion, false); err != nil {
		t.Fatalf("WriteDefault: %v", err)
	}
	return dir, readConfig(t, dir)
}

func readConfig(t *testing.T, dir string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, ConfigFileName))
	if err != nil {
		t.Fatalf("reading %s: %v", ConfigFileName, err)
	}
	return data
}

func seedConfig(t *testing.T, body string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, ConfigFileName), []byte(body), 0644); err != nil {
		t.Fatalf("seeding %s: %v", ConfigFileName, err)
	}
	return dir
}

