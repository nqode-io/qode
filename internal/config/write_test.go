	t.Setenv("USERPROFILE", home)

	userCfg := filepath.Join(home, QodeDir, "config.yaml")
	if err := os.MkdirAll(filepath.Dir(userCfg), 0755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
